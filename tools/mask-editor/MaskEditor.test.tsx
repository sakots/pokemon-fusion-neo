import { render, screen, fireEvent, waitFor, act } from '@testing-library/react';
import { expect, it, vi } from 'vitest';
import { readFileSync } from 'node:fs';
import { PNG } from 'pngjs';
import { MaskEditor } from './MaskEditor';
import type { Raster } from '../../scripts/fusion-materials';
import { prepareMask } from '../../scripts/mask-definition';
vi.mock('./RasterCanvas', () => ({ RasterCanvas: ({ label, onPoint }: { label: string; onPoint?: (x: number, y: number) => void }) =>
  <button onClick={event => onPoint?.(event.clientX || 43, event.clientY || 52)}>{label}</button> }));
const original = PNG.sync.read(readFileSync('public/assets/pokemon/1.png'));
it('1025種類を探せ、既存定義のプレビューと不正JSONによる保存制御を行う', async () => {
  render(<MaskEditor loadRaster={async () => original} />);
  await waitFor(() => expect(screen.getByRole('button', { name: 'JSONを保存' })).toBeEnabled());
  expect(screen.getByText('頭のプレビュー')).toBeInTheDocument();
  const editor = screen.getByLabelText('部位定義JSON');
  const saved = (editor as HTMLTextAreaElement).value;
  fireEvent.change(editor, { target: { value: '{' } });
  expect(screen.getByRole('button', { name: 'JSONを保存' })).toBeDisabled();
  expect(screen.getByRole('alert')).toBeInTheDocument();
  fireEvent.change(editor, { target: { value: saved } });
  expect(screen.getByRole('button', { name: 'JSONを保存' })).toBeEnabled();
  fireEvent.change(screen.getByLabelText('クリックの用途'), { target: { value: 'bodyAnchor' } });
  fireEvent.click(screen.getByText('元画像'));
  expect(JSON.parse((editor as HTMLTextAreaElement).value).bodyAnchor).toEqual({ x: 43, y: 52 });
  fireEvent.change(screen.getByLabelText('番号・名前で検索'), { target: { value: '１０２５' } });
  expect(screen.getByRole('option', { name: /1025.*モモワロウ/ })).toBeInTheDocument();
  fireEvent.change(screen.getByLabelText('編集対象'), { target: { value: '1025' } });
  await waitFor(() => expect(JSON.parse((editor as HTMLTextAreaElement).value).id).toBe(1025));
  expect(screen.getByRole('button', { name: 'JSONを保存' })).toBeDisabled();
});
it('対象変更後は前の読込結果を反映せず、現在の読込失敗を表示する', async () => {
  let complete!: (source: Raster) => void;
  const load = vi.fn().mockImplementationOnce(() => new Promise<Raster>(resolve => { complete = resolve; }))
    .mockRejectedValueOnce(new Error('画像を読み込めません'));
  render(<MaskEditor loadRaster={load} />);
  fireEvent.change(screen.getByLabelText('編集対象'), { target: { value: '4' } });
  await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent('画像を読み込めません'));
  await act(async () => complete(original));
  expect(screen.getByRole('alert')).toHaveTextContent('画像を読み込めません');
  expect(screen.getByRole('button', { name: 'JSONを保存' })).toBeDisabled();
});

it('頭の最後の点だけを削除し、3点未満・空・不正JSONでは保存や削除を制御する', async () => {
  render(<MaskEditor loadRaster={async () => original} />);
  await waitFor(() => expect(screen.getByRole('button', { name: 'JSONを保存' })).toBeEnabled());
  const editor = screen.getByLabelText('部位定義JSON') as HTMLTextAreaElement;
  const initial = JSON.parse(editor.value);
  fireEvent.click(screen.getByText('元画像'));
  expect(JSON.parse(editor.value).headPolygon).toEqual([...initial.headPolygon, [43, 52]]);
  const remove = screen.getByRole('button', { name: '頭の最後の点を削除' });
  fireEvent.change(screen.getByLabelText('クリックの用途'), { target: { value: 'bodyAnchor' } });
  fireEvent.click(remove);
  expect(JSON.parse(editor.value)).toEqual(initial);
  fireEvent.change(editor, { target: { value: JSON.stringify({ ...initial, headPolygon: initial.headPolygon.slice(0, 3) }) } });
  fireEvent.click(remove);
  expect(JSON.parse(editor.value).headPolygon).toHaveLength(2);
  expect(screen.queryByText('頭のプレビュー')).not.toBeInTheDocument();
  expect(screen.getByRole('button', { name: 'JSONを保存' })).toBeDisabled();
  fireEvent.click(remove);
  fireEvent.click(remove);
  expect(JSON.parse(editor.value)).toEqual({ ...initial, headPolygon: [] });
  expect(remove).toBeDisabled();
  fireEvent.change(editor, { target: { value: '{' } });
  expect(remove).toBeDisabled();
  fireEvent.click(remove);
  expect(editor.value).toBe('{');
  fireEvent.change(editor, { target: { value: JSON.stringify({ ...initial, headPolygon: null }) } });
  expect(remove).toBeDisabled();
});

it('クリックで指定した保護領域を既存領域に追加し、対象の皮膚色を変換から除外する', async () => {
  render(<MaskEditor loadRaster={async () => original} />);
  await waitFor(() => expect(screen.getByRole('button', { name: 'JSONを保存' })).toBeEnabled());
  const editor = screen.getByLabelText('部位定義JSON') as HTMLTextAreaElement;
  const initial = JSON.parse(editor.value);
  const before = prepareMask(original, initial);
  const index = before.bodyPixels[0];
  const x = initial.bodyAnchor.x - before.parts.body.anchor.x + index % before.parts.body.width;
  const y = initial.bodyAnchor.y - before.parts.body.anchor.y + Math.floor(index / before.parts.body.width);
  const polygon = [[x, y], [x + 2, y], [x, y + 2]];
  const existing = [[10, 10], [12, 10], [10, 12]];
  fireEvent.change(editor, { target: { value: JSON.stringify({ ...initial, bodyProtectedPolygons: [existing] }) } });
  fireEvent.change(screen.getByLabelText('クリックの用途'), { target: { value: 'bodyProtectedPolygon' } });
  const add = screen.getByRole('button', { name: '保護領域を追加' });
  expect(add).toBeDisabled();
  for (const [pointX, pointY] of polygon.slice(0, 2)) fireEvent.click(screen.getByText('元画像'), { clientX: pointX, clientY: pointY });
  expect(add).toBeDisabled();
  expect(screen.getByRole('button', { name: 'JSONを保存' })).toBeDisabled();
  expect(JSON.parse(editor.value).bodyProtectedPolygons).toEqual([existing]);
  fireEvent.click(screen.getByText('元画像'), { clientX: polygon[2][0], clientY: polygon[2][1] });
  expect(add).toBeEnabled();
  fireEvent.click(add);
  const edited = JSON.parse(editor.value);
  expect(edited).toEqual({ ...initial, bodyProtectedPolygons: [existing, polygon] });
  expect(prepareMask(original, edited).bodyPixels).not.toContain(index);
  expect(screen.getByRole('button', { name: 'JSONを保存' })).toBeEnabled();
  expect(add).toBeDisabled();
});
it('用途・JSON・対象を変更すると未確定の保護領域を破棄し、不正JSONで追加できない', async () => {
  render(<MaskEditor loadRaster={async () => original} />);
  await waitFor(() => expect(screen.getByRole('button', { name: 'JSONを保存' })).toBeEnabled());
  const mode = screen.getByLabelText('クリックの用途');
  const editor = screen.getByLabelText('部位定義JSON') as HTMLTextAreaElement;
  const saved = editor.value;
  const add = screen.getByRole('button', { name: '保護領域を追加' });
  const draw = () => { for (let x = 10; x <= 12; x++) fireEvent.click(screen.getByText('元画像'), { clientX: x, clientY: 10 }); };
  fireEvent.change(mode, { target: { value: 'bodyProtectedPolygon' } });
  draw();
  expect(add).toBeEnabled();
  fireEvent.change(mode, { target: { value: 'headAnchor' } });
  fireEvent.change(mode, { target: { value: 'bodyProtectedPolygon' } });
  expect(add).toBeDisabled();
  expect(editor.value).toBe(saved);
  draw();
  fireEvent.change(editor, { target: { value: '{' } });
  expect(add).toBeDisabled();
  fireEvent.click(add);
  expect(editor.value).toBe('{');
  fireEvent.change(editor, { target: { value: saved } });
  expect(add).toBeDisabled();
  draw();
  fireEvent.change(screen.getByLabelText('編集対象'), { target: { value: '4' } });
  expect(add).toBeDisabled();
  expect(JSON.parse(editor.value).bodyProtectedPolygons).toHaveLength(1);
});

it('クリックと補完色で既存の補完領域に追加し、体の穴を塗って頭を保つ', async () => {
  render(<MaskEditor loadRaster={async () => original} />);
  await waitFor(() => expect(screen.getByRole('button', { name: 'JSONを保存' })).toBeEnabled());
  const editor = screen.getByLabelText('部位定義JSON') as HTMLTextAreaElement;
  const initial = JSON.parse(editor.value);
  const before = prepareMask(original, initial);
  fireEvent.change(screen.getByLabelText('クリックの用途'), { target: { value: 'bodyPatch' } });
  fireEvent.change(screen.getByLabelText('補完色'), { target: { value: '#abcdef' } });
  const add = screen.getByRole('button', { name: '補完領域を追加' });
  const polygon = [[38, 40], [42, 40], [38, 44]];
  for (const [x, y] of polygon.slice(0, 2)) fireEvent.click(screen.getByText('元画像'), { clientX: x, clientY: y });
  expect(add).toBeDisabled();
  expect(screen.getByRole('button', { name: 'JSONを保存' })).toBeDisabled();
  expect(JSON.parse(editor.value)).toEqual(initial);
  fireEvent.click(screen.getByText('元画像'), { clientX: 38, clientY: 44 });
  expect(add).toBeEnabled();
  fireEvent.click(add);
  const edited = JSON.parse(editor.value);
  expect(edited).toEqual({ ...initial, patches: [...initial.patches, { polygon, color: [171, 205, 239, 255] }] });
  const after = prepareMask(original, edited);
  expect(after.parts.head.data).toEqual(before.parts.head.data);
  const pixel = (body: typeof after.parts.body) => {
    const x = 39 - initial.bodyAnchor.x + body.anchor.x;
    const y = 41 - initial.bodyAnchor.y + body.anchor.y;
    return Array.from(body.data.subarray((y * body.width + x) * 4, (y * body.width + x) * 4 + 4));
  };
  expect(pixel(before.parts.body)[3]).toBe(0);
  expect(pixel(after.parts.body)).toEqual([171, 205, 239, 255]);
  expect(add).toBeDisabled();
  expect(screen.getByRole('button', { name: 'JSONを保存' })).toBeEnabled();
});
